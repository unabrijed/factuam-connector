#!/usr/bin/env node
/**
 * Hackathon single-node AXL: one Go `axl/node` (orchestrator config, HTTP :9002) + one unified TS worker.
 * Writes `.env.local.axl` with GENSYN_AXL_SINGLE_NODE, AXL_SINGLE_PEER_ID, GENSYN_AXL_API_URL.
 *
 * Usage:
 *   yarn local:axl:single              # node + env + unified worker
 *   yarn local:axl:single --nodes-only   # node + env only
 */
import { spawn, spawnSync } from "node:child_process";
import fs from "node:fs";
import http from "node:http";
import net from "node:net";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LOCAL_AX_NODES, ORCHESTRATOR_API_PORT, axlNodeBinaryPath, nodeConfigPath, repoRoot } from "./axl-local-topology.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const nodesOnly = process.argv.includes("--nodes-only");
const envOutPath = path.join(repoRoot, ".env.local.axl");

const orchestrator = LOCAL_AX_NODES.find((n) => n.id === "orchestrator");
if (!orchestrator) {
  console.error("[local:axl:single] internal: missing orchestrator in LOCAL_AX_NODES");
  process.exit(1);
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function fetchPublicKey(apiPort) {
  return new Promise((resolve) => {
    const req = http.request(
      {
        hostname: "127.0.0.1",
        port: apiPort,
        path: "/topology",
        method: "GET",
        timeout: 3000
      },
      (res) => {
        let buf = "";
        res.setEncoding("utf8");
        res.on("data", (chunk) => {
          buf += chunk;
        });
        res.on("end", () => {
          if (res.statusCode !== 200) {
            resolve(null);
            return;
          }
          try {
            const body = JSON.parse(buf);
            const key = body?.our_public_key;
            resolve(typeof key === "string" && /^[0-9a-f]{64}$/i.test(key) ? key : null);
          } catch {
            resolve(null);
          }
        });
      }
    );
    req.on("error", () => resolve(null));
    req.on("timeout", () => {
      req.destroy();
      resolve(null);
    });
    req.end();
  });
}

function checkListenPortFree(port, host = "127.0.0.1") {
  return new Promise((resolve, reject) => {
    const srv = net.createServer();
    srv.once("error", (err) => {
      if (/** @type {NodeJS.ErrnoException} */ (err).code === "EADDRINUSE") resolve(false);
      else reject(err);
    });
    srv.listen({ port, host }, () => {
      srv.close(() => resolve(true));
    });
  });
}

function spawnNodeChild(bin, node) {
  const cfg = nodeConfigPath(node);
  const cwd = path.dirname(cfg);
  const child = spawn(bin, ["-config", path.basename(cfg)], {
    cwd,
    stdio: "inherit",
    env: process.env
  });
  nodeChildren.push(child);
  child.on("exit", (code, signal) => {
    if (signal === "SIGTERM") return;
    console.error(`[local:axl:single] axl node ${node.id} exited code=${code ?? "null"} signal=${signal ?? "null"}`);
    stopAll(code ?? 1);
  });
  return child;
}

async function waitForPublicKeyOnPort(apiPort, label, deadlineMs) {
  const deadline = Date.now() + deadlineMs;
  while (Date.now() < deadline) {
    const k = await fetchPublicKey(apiPort);
    if (k) return k;
    await sleep(200);
  }
  console.error(`[local:axl:single] timeout waiting for /topology on ${label} (port ${apiPort})`);
  return null;
}

function ensureGoBinary() {
  const bin = axlNodeBinaryPath();
  if (fs.existsSync(bin)) return bin;
  console.log("[local:axl:single] building axl/node (first run)…");
  const axlDir = path.join(repoRoot, "axl");
  const r = spawnSync("make", ["build"], {
    cwd: axlDir,
    stdio: "inherit",
    env: { ...process.env, GOTOOLCHAIN: process.env.GOTOOLCHAIN || "go1.25.5" }
  });
  if (r.status !== 0 || !fs.existsSync(bin)) {
    console.error("[local:axl:single] Go build failed. From axl/: run `make build`.");
    process.exit(1);
  }
  return bin;
}

function writeSingleEnvFile(peerHex) {
  const lines = [
    "# Generated by `yarn local:axl:single`. Restart the API after changes.",
    "GENSYN_AXL_API_URL=http://127.0.0.1:9002",
    "GENSYN_AXL_SINGLE_NODE=true",
    `AXL_SINGLE_PEER_ID=${peerHex}`,
    ""
  ];
  fs.writeFileSync(envOutPath, lines.join("\n"), "utf8");
  console.log(`[local:axl:single] wrote ${path.relative(repoRoot, envOutPath)}`);
}

const nodeChildren = [];
const yarnChildren = [];

function stopAll(code = 0) {
  for (const c of yarnChildren) {
    try {
      c.kill("SIGTERM");
    } catch {
      /* ignore */
    }
  }
  for (const c of nodeChildren) {
    try {
      c.kill("SIGTERM");
    } catch {
      /* ignore */
    }
  }
  setTimeout(() => process.exit(code), 1200).unref();
}

async function main() {
  const r = spawnSync(process.execPath, [path.join(__dirname, "ensure-axl-local-keys.mjs")], {
    stdio: "inherit",
    cwd: repoRoot
  });
  if (r.status !== 0) {
    process.exit(r.status ?? 1);
  }

  const orchCfg = nodeConfigPath(orchestrator);
  if (!fs.existsSync(orchCfg)) {
    console.error(`[local:axl:single] missing config ${orchCfg}`);
    process.exit(1);
  }

  if (!(await checkListenPortFree(ORCHESTRATOR_API_PORT))) {
    console.error(
      `[local:axl:single] HTTP port ${ORCHESTRATOR_API_PORT} is in use. Stop the other process (\`lsof -i :9002\`) and retry.`
    );
    process.exit(1);
  }

  const bin = ensureGoBinary();

  console.log("[local:axl:single] starting single Go AXL node (orchestrator config on :9002)…");
  spawnNodeChild(bin, orchestrator);

  const peerHex = await waitForPublicKeyOnPort(ORCHESTRATOR_API_PORT, "orchestrator", 25_000);
  if (!peerHex) {
    console.error("[local:axl:single] could not read our_public_key from /topology.");
    stopAll(1);
    return;
  }

  writeSingleEnvFile(peerHex);

  const sharedEnv = {
    ...process.env,
    GENSYN_AXL_API_URL: "http://127.0.0.1:9002",
    GENSYN_AXL_SINGLE_NODE: "true",
    AXL_SINGLE_PEER_ID: peerHex
  };

  if (!nodesOnly) {
    const child = spawn("yarn", ["workspace", "@factuam/api", "dev:axl-unified"], {
      stdio: "inherit",
      env: sharedEnv,
      cwd: repoRoot
    });
    yarnChildren.push(child);
    child.on("exit", (code, signal) => {
      if (signal === "SIGTERM") return;
      console.error(
        `[local:axl:single] unified worker exited code=${code ?? "null"} signal=${signal ?? "null"}`
      );
      stopAll(code ?? 1);
    });
    console.log("[local:axl:single] unified AXL worker running. Restart the API to load .env.local.axl.");
  } else {
    console.log("[local:axl:single] --nodes-only: start unified worker with `yarn dev:axl-unified` after API restart.");
  }

  process.on("SIGINT", () => stopAll(0));
  process.on("SIGTERM", () => stopAll(0));
}

main().catch((e) => {
  console.error(e);
  stopAll(1);
});
